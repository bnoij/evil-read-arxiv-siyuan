#!/usr/bin/env python3
import argparse
import json
import re
import sys
from pathlib import Path

import yaml

SCRIPT_DIR = Path(__file__).resolve().parent
if str(SCRIPT_DIR) not in sys.path:
    sys.path.insert(0, str(SCRIPT_DIR))

from build_job import ensure_papers_job, write_documents_job
from siyuan_job_client import SiYuanJobClient, canonical_document_markdown, content_fingerprint, stable_hash

WORKFLOW_NAME = "evil-read-arxiv"


def paper_identity(paper):
    arxiv_id = re.sub(r"v\d+$", "", str(paper.get("arxiv_id") or paper.get("arxivId") or ""), flags=re.IGNORECASE)
    if arxiv_id:
        return arxiv_id.lower()
    return re.sub(r"[^a-z0-9\u4e00-\u9fff]+", "", str(paper.get("title") or "").lower())


def render_daily_markdown(target_date, overview, papers, language="zh"):
    english = language == "en"
    lines = [f"# {target_date} {'Paper Recommendations' if english else '论文推荐'}", ""]
    overview_heading = "Today's Overview" if english else "今日概览"
    lines.extend([f"## {overview_heading}", "", overview or "--", ""])
    for paper in papers:
        lines.extend([f"### {paper.get('title', '--')}", ""])
        authors = paper.get("authors") or []
        lines.append(f"- **{'Authors' if english else '作者'}**: {', '.join(authors) if authors else '--'}")
        lines.append(f"- **{'Published' if english else '发布时间'}**: {paper.get('published') or '--'}")
        if paper.get("venue"):
            lines.append(f"- **{'Venue' if english else '会议/期刊'}**: {paper['venue']}")
        score = (paper.get("scores") or {}).get("recommendation", paper.get("score", "--"))
        lines.append(f"- **{'Recommendation score' if english else '推荐评分'}**: {score}")
        links = []
        if paper.get("url"):
            links.append(f"[arXiv]({paper['url']})" if paper.get("arxiv_id") else f"[Source]({paper['url']})")
        if paper.get("pdf_url"):
            links.append(f"[PDF]({paper['pdf_url']})")
        if paper.get("itemKey"):
            links.append(f"[Zotero](zotero://select/library/items/{paper['itemKey']})")
        if paper.get("noteDocId"):
            links.append(f"[{'Note' if english else '思源笔记'}](siyuan://blocks/{paper['noteDocId']})")
        lines.append(f"- **{'Links' if english else '链接'}**: {' | '.join(links) if links else '--'}")
        lines.extend(["", f"**{'One-line summary' if english else '一句话总结'}**: {paper.get('summary') or '--'}", ""])
        contributions = paper.get("contributions") or []
        if contributions:
            lines.append(f"**{'Core contributions' if english else '核心贡献/观点'}**:")
            lines.extend(f"- {item}" for item in contributions)
            lines.append("")
        if paper.get("key_results"):
            lines.extend([f"**{'Key results' if english else '关键结果'}**: {paper['key_results']}", ""])
        for asset in paper.get("assets") or []:
            lines.extend([f"![{paper.get('title', 'Figure')}]({asset})", ""])
        lines.extend(["---", ""])
    return "\n".join(lines).rstrip() + "\n"


def render_graph_markdown(papers):
    lines = ["# PaperGraph", "", "Generated by evil-read-arxiv. Links open the corresponding SiYuan Note.", ""]
    for paper in papers:
        if not paper.get("noteDocId"):
            continue
        score = (paper.get("scores") or {}).get("recommendation", "--")
        lines.append(f"- [{paper.get('title', '--')}](siyuan://blocks/{paper['noteDocId']}) — {paper.get('matched_domain') or paper.get('domain') or '--'}; score {score}; Zotero `{paper.get('itemKey', '--')}`")
    return "\n".join(lines).rstrip() + "\n"


def _write_target(markdown, doc_id="", path="", attrs=None):
    return {
        "docId": doc_id,
        "path": path,
        "markdown": markdown,
        "attrs": attrs or {},
    }


def prepare_write_documents(papers, daily_path, graph_path, daily_markdown, graph_markdown, state_provider, force=False):
    targets = []
    for paper in papers:
        if not paper.get("analysis_markdown") or not paper.get("noteDocId"):
            continue
        attrs = {
            "custom-research-workflow": WORKFLOW_NAME,
            "custom-research-document-id": paper_identity(paper),
            "custom-research-analysis-source": "kimi",
        }
        targets.append((paper["noteDocId"], _write_target(paper["analysis_markdown"], doc_id=paper["noteDocId"], attrs=attrs)))
    if daily_path:
        targets.append((daily_path, _write_target(daily_markdown, path=daily_path, attrs={"custom-research-workflow": WORKFLOW_NAME})))
    if graph_path:
        targets.append((graph_path, _write_target(graph_markdown, path=graph_path, attrs={"custom-research-workflow": WORKFLOW_NAME})))
    documents = []
    decisions = {}
    for key, target in targets:
        state = state_provider(doc_id=target["docId"], path=target["path"])
        attrs = state.get("attrs") or {}
        current_hash = state.get("contentHash") or stable_hash("")
        decision = {"status": "write", "state": state}
        operation = None
        if not state.get("exists"):
            operation = {**target, "expectedHash": None, "onConflict": "report"}
        elif force:
            operation = {**target, "expectedHash": current_hash, "onConflict": "overwrite"}
        elif state.get("empty", current_hash == stable_hash("")):
            operation = {**target, "expectedHash": current_hash, "onConflict": "report"}
        else:
            managed = attrs.get("custom-research-workflow") == WORKFLOW_NAME and attrs.get("custom-research-content-hash") == current_hash
            new_hash = stable_hash(canonical_document_markdown(target["markdown"]))
            same_content = current_hash == new_hash
            if state.get("contentFingerprint"):
                same_content = state["contentFingerprint"] == content_fingerprint(target["markdown"])
            if managed and same_content:
                decision["status"] = "unchanged"
            else:
                decision["status"] = "preserved"
        if operation:
            documents.append(operation)
        decisions[key] = decision
    return documents, decisions


def run_daily_workflow(client, config, ranked, overview, target_date, force=False):
    papers = [dict(paper) for paper in ranked.get("top_papers", [])]
    ensure_job = ensure_papers_job(papers)
    ensure_id = client.submit_job(ensure_job)
    ensure_result = client.wait_for_job(ensure_id, timeout=config.get("siyuan", {}).get("job_timeout", 900))
    ensured = (ensure_result.get("result") or {}).get("papers") or []
    by_identity = {paper_identity(paper): paper for paper in ensured}
    for paper in papers:
        match = by_identity.get(paper_identity(paper))
        if match:
            paper.update(match)
    siyuan = config.get("siyuan", {})
    language = config.get("language", "zh")
    daily_root = siyuan.get("daily_root", "/Research/Daily").rstrip("/")
    title = "paper-recommendations" if language == "en" else "论文推荐"
    daily_path = f"{daily_root}/{target_date} {title}"
    daily_markdown = render_daily_markdown(target_date, overview, papers, language)
    graph_markdown = render_graph_markdown(papers)
    documents, decisions = prepare_write_documents(
        papers,
        daily_path,
        siyuan.get("graph_path", "/Research/PaperGraph"),
        daily_markdown,
        graph_markdown,
        client.get_document_state,
        force=force,
    )
    write_result = {"status": "completed", "result": {"documents": []}}
    if documents:
        write_id = client.submit_job(write_documents_job(documents))
        write_result = client.wait_for_job(write_id, timeout=siyuan.get("job_timeout", 900))
    return {
        "status": "partial" if "partial" in (ensure_result.get("status"), write_result.get("status")) or "failed" in (ensure_result.get("status"), write_result.get("status")) else "completed",
        "papers": papers,
        "dailyDocPath": daily_path,
        "decisions": decisions,
        "ensureStatus": ensure_result.get("status"),
        "writeStatus": write_result.get("status"),
        "writeResults": (write_result.get("result") or {}).get("documents") or [],
    }


def run_paper_analysis(client, config, paper, force=False):
    paper = dict(paper)
    ensure_id = client.submit_job(ensure_papers_job([paper]))
    ensure_result = client.wait_for_job(ensure_id, timeout=config.get("siyuan", {}).get("job_timeout", 900))
    ensured = ((ensure_result.get("result") or {}).get("papers") or [{}])[0]
    paper.update(ensured)
    if not paper.get("noteDocId"):
        raise RuntimeError(paper.get("error") or "The plugin did not return a Note document ID")
    siyuan = config.get("siyuan", {})
    documents, decisions = prepare_write_documents(
        [paper],
        "",
        siyuan.get("graph_path", "/Research/PaperGraph"),
        "",
        render_graph_markdown([paper]),
        client.get_document_state,
        force=force,
    )
    write_result = {"status": "completed", "result": {"documents": []}}
    if documents:
        write_id = client.submit_job(write_documents_job(documents))
        write_result = client.wait_for_job(write_id, timeout=siyuan.get("job_timeout", 900))
    return {
        "status": "partial" if "partial" in (ensure_result.get("status"), write_result.get("status")) or "failed" in (ensure_result.get("status"), write_result.get("status")) else "completed",
        "noteDocId": paper["noteDocId"],
        "parentDocId": paper.get("parentDocId", ""),
        "itemKey": paper.get("itemKey", ""),
        "decisions": decisions,
        "writeResults": (write_result.get("result") or {}).get("documents") or [],
    }


def emit_json(value):
    rendered = json.dumps(value, ensure_ascii=False, indent=2, default=str) + "\n"
    sys.stdout.buffer.write(rendered.encode("utf-8"))


def main():
    parser = argparse.ArgumentParser(description="Run the two-stage Kimi to SiYuan/Zotero daily workflow")
    parser.add_argument("--config", required=True)
    parser.add_argument("--ranked", required=True)
    parser.add_argument("--overview", default="")
    parser.add_argument("--overview-file", default="")
    parser.add_argument("--target-date", required=True)
    parser.add_argument("--single", action="store_true", help="Import one analysis without creating a daily document")
    parser.add_argument("--force", action="store_true")
    args = parser.parse_args()
    config = yaml.safe_load(Path(args.config).read_text(encoding="utf-8")) or {}
    ranked = json.loads(Path(args.ranked).read_text(encoding="utf-8"))
    overview = Path(args.overview_file).read_text(encoding="utf-8") if args.overview_file else args.overview
    client = SiYuanJobClient(config.get("siyuan", {}).get("base_url", "http://127.0.0.1:6806"))
    if args.single:
        if len(ranked.get("top_papers", [])) != 1:
            parser.error("--single requires exactly one paper in ranked JSON")
        result = run_paper_analysis(client, config, ranked["top_papers"][0], force=args.force)
    else:
        result = run_daily_workflow(client, config, ranked, overview, args.target_date, force=args.force)
    emit_json(result)
    return 0 if result["status"] == "completed" else 2


if __name__ == "__main__":
    sys.exit(main())
